#!/usr/bin/env python
"""Trace -> oracle.json for layout_spring_layout_m6_calls (M6_InterProceduralCFG).

Answer: per-function invocation counts (Python `call` events) for every
function defined with `def` in networkx/drawing/layout.py (module-level and
nested), summed over all test methods of TestSpringLayoutCallGraph.
"""

import argparse
import ast
import json
import re
import sys
from collections import Counter
from pathlib import Path

REL_FILE = "networkx/drawing/layout.py"
MODULE = "networkx.drawing.layout"
TARGET = f"{MODULE}.spring_layout"
TEST_FILE = "networkx_qa/layout_spring_layout_m6_calls/files/testcase.py"
TEST_CLASS = "TestSpringLayoutCallGraph"

LINE_RE = re.compile(r"^\S+ \S+ (?P<file>\S+):(?P<lineno>\d+) (?P<func>\S+) event=(?P<event>\w+)")


def fail(msg):
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def scope_qualnames(source_path):
    tree = ast.parse(source_path.read_text(encoding="utf-8"))
    names = []

    def visit(node, prefix):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                qual = f"{prefix}{child.name}"
                names.append(qual)
                visit(child, f"{qual}.<locals>.")
            elif isinstance(child, ast.ClassDef):
                visit(child, f"{prefix}{child.name}.")
            else:
                visit(child, prefix)

    visit(tree, "")
    return sorted({f"{MODULE}.{q}" for q in names})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trace-log", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    trace = Path(args.trace_log)
    if not trace.is_file():
        fail(f"trace log missing: {trace}")
    text = trace.read_text(encoding="utf-8", errors="replace")
    if not text.strip():
        fail(f"trace log empty: {trace}")

    source = Path(__file__).resolve().parents[3] / REL_FILE
    if not source.is_file():
        source = Path("/testbed") / REL_FILE
    scope = scope_qualnames(source)
    scope_set = set(scope)

    counts = Counter()
    for line in text.splitlines():
        m = LINE_RE.match(line)
        if not m or m.group("event") != "call":
            continue
        if not m.group("file").replace("\\", "/").endswith(REL_FILE):
            continue
        func = m.group("func")
        if func in scope_set:
            counts[func] += 1

    if counts[TARGET] == 0:
        fail(f"no call events for {TARGET} in trace")

    answer = {
        "invocation_counts": [
            {"count": counts[f], "file": REL_FILE, "func": f} for f in scope
        ]
    }

    question = (
        f"Run the pytest test class `{TEST_FILE}::{TEST_CLASS}` (all of its test "
        "methods, each of which calls `networkx.drawing.layout.spring_layout` "
        f"from `{REL_FILE}` directly). Consider every function defined with a "
        f"`def` statement anywhere in `{REL_FILE}`: all module-level functions AND "
        "all functions nested inside other functions (closures/inner functions). "
        "Lambdas, comprehensions and generator expressions are NOT functions for "
        "this question and must not appear. Module-level aliases (a second name "
        "bound to an existing function object) are not separate entries; the "
        "argmap/decorator wrapper code generated by `networkx.utils.decorators` "
        "lives outside this file and is not counted; only the decorated function's "
        "own body frame counts. "
        "For each such function, report how many times it was invoked, where one "
        "invocation = one Python `call` event (as seen by `sys.settrace`) for a "
        "frame executing that function's own code object, regardless of who "
        "called it (direct, transitive, recursive, or via a library such as "
        "scipy calling back into it), and including invocations that end by "
        "raising an exception. None of the in-scope functions are generators, so "
        "there are no resumptions. Counts are summed over ALL test methods in "
        "the class (run in a single pytest session); nothing that happens outside "
        "the test methods themselves is counted. Functions in scope that never "
        "run must still be listed with `count: 0`.\n\n"
        "Answer as JSON: {\"invocation_counts\": [{\"count\": int, \"file\": str, "
        "\"func\": str}, ...]} with exactly one entry per in-scope function. "
        f"`file` is always the repo-relative path `{REL_FILE}`. `func` is the "
        "dotted module path followed by the function's `__qualname__`, e.g. a "
        "function `g` nested in module-level `f` of module `pkg.mod` is "
        "`pkg.mod.f.<locals>.g`, and a module-level function `h` is `pkg.mod.h`. "
        "`count` is a JSON integer. Sort entries by `func` ascending (plain "
        "Python string ordering; qualnames are unique so no tie-break is needed)."
    )

    oracle = {
        "question_kind": "M6_InterProceduralCFG",
        "question": question,
        "template_answer": {
            "invocation_counts": [{"count": "int", "file": "str", "func": "str"}]
        },
        "oracle_answer": answer,
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(oracle, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    print(json.dumps(answer, indent=2))


if __name__ == "__main__":
    main()
