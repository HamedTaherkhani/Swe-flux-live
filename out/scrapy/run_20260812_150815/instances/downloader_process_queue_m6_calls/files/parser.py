#!/usr/bin/env python3
from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from collections import Counter
from pathlib import Path


TARGET_FILE = "scrapy/core/downloader/__init__.py"
TARGET_FUNC = "scrapy.core.downloader.Downloader._process_queue"
MODULE = "scrapy.core.downloader"
TRACKED_CLASSES = ("Slot", "Downloader")

QUESTION = """Run every pytest test method in `scrapy_qa/downloader_process_queue_m6_calls/files/testcase.py::TestDownloaderQueueCallGraph`; equivalently, aggregate the run across all pytest ids of the form `scrapy_qa/downloader_process_queue_m6_calls/files/testcase.py::TestDownloaderQueueCallGraph::test_*`. The target is `scrapy.core.downloader.Downloader._process_queue` in `scrapy/core/downloader/__init__.py`. Across that whole class run, how many Python `call` events occur for each function in the scope defined below?

The tracked scope is every function whose `def` or `async def` statement is an immediate child of either the `Slot` class body or the `Downloader` class body in `scrapy/core/downloader/__init__.py`, as that file exists in the repository. Include explicitly defined `__init__` and other dunder methods. Exclude module-level functions, nested functions, closures, comprehension code objects, properties without an immediate-child function definition of their own, inherited methods, and methods synthesized at runtime (including methods generated by `dataclasses`). Decorators do not change scope membership: identify the immediate-child function defined by the source statement, not any wrapper code defined in another file.

Function identity is the full dotted `module.qualname`, including the class name; for example, a hypothetical method `close` on `scrapy.http.Response` would be `scrapy.http.Response.close`. A function's count is the total number of Python `call` trace events delivered for that function's frame during all test methods in the named class, including events caused directly, transitively, recursively, or from any other frame. A `call` event emitted when an already-created generator or coroutine frame resumes after suspension counts as another invocation event. Calls to functions outside the defined scope are ignored. A scoped function that never executes must still appear with `count: 0`. Preserve and count all repeated events; do not deduplicate. Sum counts over the whole test-class run rather than reporting per-method counts; test execution order does not affect this aggregation.

Return exactly one JSON object with key `invocation_counts`. Its value is a JSON array containing one object for every scoped function, and each object has exactly the keys `count`, `file`, and `func`. `count` is a JSON integer. `file` is the literal repository-relative POSIX path `scrapy/core/downloader/__init__.py`, and `func` uses the dotted identity format above; both are emitted directly as JSON strings, without applying Python `repr()` or `str()`. Sort entries by `func` ascending using ordinary Unicode code-point string order; if two entries ever share the same `func`, break the tie by `file` ascending. Do not otherwise reorder or remove entries."""

TRACE_RE = re.compile(
    r"\s(?P<file>/\S+):(?P<line>\d+)\s+"
    r"(?P<func>\S+)\s+event=(?P<event>call|line|return|exception)\b"
)


def discover_functions(source_path: Path) -> list[str]:
    tree = ast.parse(source_path.read_text(encoding="utf-8"), filename=str(source_path))
    functions = []
    classes = {
        node.name: node
        for node in tree.body
        if isinstance(node, ast.ClassDef) and node.name in TRACKED_CLASSES
    }
    missing = sorted(set(TRACKED_CLASSES) - set(classes))
    if missing:
        raise RuntimeError(f"tracked classes missing from source: {missing}")

    for class_name in TRACKED_CLASSES:
        for node in classes[class_name].body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                functions.append(f"{MODULE}.{class_name}.{node.name}")
    if not functions:
        raise RuntimeError("tracked scope contains no source-defined functions")
    if TARGET_FUNC not in functions:
        raise RuntimeError(f"target function is not in discovered scope: {TARGET_FUNC}")
    return sorted(functions)


def parse_trace(trace_path: Path, scoped_functions: list[str]) -> dict:
    if not trace_path.exists():
        raise RuntimeError(f"trace log is missing: {trace_path}")
    if trace_path.stat().st_size == 0:
        raise RuntimeError(f"trace log is empty: {trace_path}")

    scoped_set = set(scoped_functions)
    counts: Counter[str] = Counter()
    target_events = 0
    parsed_events = 0
    for raw_line in trace_path.read_text(encoding="utf-8").splitlines():
        match = TRACE_RE.search(raw_line)
        if not match:
            continue
        file_name = match.group("file").replace("\\", "/")
        if not file_name.endswith(TARGET_FILE):
            continue
        parsed_events += 1
        func = match.group("func")
        if func == TARGET_FUNC:
            target_events += 1
        if match.group("event") == "call" and func in scoped_set:
            counts[func] += 1

    if parsed_events == 0:
        raise RuntimeError(f"trace contains zero events from {TARGET_FILE}")
    if target_events == 0:
        raise RuntimeError(
            f"trace contains zero events for target {TARGET_FUNC} in {TARGET_FILE}"
        )

    entries = [
        {"count": counts[func], "file": TARGET_FILE, "func": func}
        for func in scoped_functions
    ]
    entries.sort(key=lambda entry: (entry["func"], entry["file"]))
    return {"invocation_counts": entries}


def main() -> None:
    argument_parser = argparse.ArgumentParser()
    argument_parser.add_argument("--trace-log", required=True, type=Path)
    argument_parser.add_argument("--out", required=True, type=Path)
    args = argument_parser.parse_args()

    source_path = Path.cwd() / TARGET_FILE
    if not source_path.is_file():
        raise RuntimeError(f"target source is missing: {source_path}")

    scoped_functions = discover_functions(source_path)
    oracle_answer = parse_trace(args.trace_log, scoped_functions)
    payload = {
        "question_kind": "M6_InterProceduralCFG",
        "question": QUESTION,
        "template_answer": {
            "invocation_counts": [{"count": "int", "file": "str", "func": "str"}]
        },
        "oracle_answer": oracle_answer,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(json.dumps(payload, indent=2, sort_keys=True))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise
